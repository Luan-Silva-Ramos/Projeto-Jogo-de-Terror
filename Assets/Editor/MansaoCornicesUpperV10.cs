        Transform roof=v05==null?null:v05.Find("Roof_WholeHouse_Joined_V05");
        Renderer roofRenderer=roof==null?null:roof.GetComponent<Renderer>();
        if(roofRenderer==null || !roof.gameObject.activeInHierarchy ||
            Mathf.Abs(roofRenderer.bounds.max.y-10.2f)>.025f ||
            Mathf.Abs(roofRenderer.bounds.min.x+10.75f)>.025f ||
            Mathf.Abs(roofRenderer.bounds.max.x-12.45f)>.025f ||
            Mathf.Abs(roofRenderer.bounds.min.z+8.75f)>.025f ||
            Mathf.Abs(roofRenderer.bounds.max.z-11.95f)>.025f)
        { Show("A cobertura V05 precisa estar ativa e nas medidas conferidas. Nada foi alterado."); return; }
        Transform v08=parent.Find("Fronton_Central_Integrated_V08");
        Transform v09=v08==null?null:v08.Find("Fronton_Plaster_Exterior_V09");
        if(v09==null || !v09.gameObject.activeInHierarchy ||
            v09.GetComponent<Renderer>()==null || v09.GetComponent<Renderer>().bounds.max.z> -4.79f)
        { Show("Mantenha o frontao V08 com a correcao V09 ativa antes deste lote. Nada foi alterado."); return; }
        Material wood=AssetDatabase.LoadAssetAtPath<Material>("Assets/_Game/Art/Materials/M_Wood_Exterior_PBR.mat");
        if(wood==null) { Show("Nao encontrei o material existente M_Wood_Exterior_PBR. Nada foi alterado."); return; }

        List<CeilingTriangle> ceilings=ReadCeilings(mansion);
        if(ceilings.Count==0) { Show("Nao consegui verificar os tetos internos. Nada foi alterado."); return; }
        string blocking;
        if(!CheckOutside(UpperCap,ceilings,out blocking) ||
           !CheckOutside(MainFascia,ceilings,out blocking) ||
           !CheckOutside(LowerBead,ceilings,out blocking))
        { Show("A verificacao encontrou uma possivel entrada sob o teto interno em "+blocking+". Nada foi alterado."); return; }

        Undo.IncrementCurrentGroup();
        int group=Undo.GetCurrentGroup();
        Undo.SetCurrentGroupName("Criar cornijas superiores V10");
        try
        {
            var root=new GameObject("Cornices_Upper_V10");
            SceneManager.MoveGameObjectToScene(root,v05.gameObject.scene);
            root.transform.SetParent(parent,false);
            Undo.RegisterCreatedObjectUndo(root,"Criar cornijas V10");
            Build("Cornice_UpperCap_V10",UpperCap,root.transform,wood);
            Build("Cornice_MainFascia_V10",MainFascia,root.transform,wood);
            Build("Cornice_LowerBead_V10",LowerBead,root.transform,wood);
            Transform oldStubs=v08.Find("Cornice_Central_LeftRight_V08");
            if(oldStubs!=null)
            {
                Undo.RecordObject(oldStubs.gameObject,"Preservar cornija central anterior");
                oldStubs.gameObject.SetActive(false);
            }
            EditorSceneManager.MarkSceneDirty(v05.gameObject.scene);
            Selection.activeGameObject=root;
