        }
    }

    private static List<CeilingTriangle> ReadCeilings(Transform mansion)
    {
        var result=new List<CeilingTriangle>();
        foreach(ProBuilderMesh mesh in mansion.GetComponentsInChildren<ProBuilderMesh>(true))
        {
            if(!mesh.gameObject.activeInHierarchy || !mesh.name.StartsWith("Ceiling_Upper_")) continue;
            Renderer renderer=mesh.GetComponent<Renderer>();
            if(renderer==null) continue;
            float underside=renderer.bounds.min.y;
            foreach(Face face in mesh.faces)
            {
                var ids=face.indexes;
                for(int i=0;i<ids.Count;i+=3)
                {
                    Vector3 a=mesh.transform.TransformPoint(mesh.positions[ids[i]]);
                    Vector3 b=mesh.transform.TransformPoint(mesh.positions[ids[i+1]]);
                    Vector3 c=mesh.transform.TransformPoint(mesh.positions[ids[i+2]]);
                    if(Mathf.Abs(a.y-underside)>.01f || Mathf.Abs(b.y-underside)>.01f ||
                       Mathf.Abs(c.y-underside)>.01f) continue;
                    float area=(b.x-a.x)*(c.z-a.z)-(b.z-a.z)*(c.x-a.x);
                    if(Mathf.Abs(area)<.000001f) continue;
                    result.Add(new CeilingTriangle {
                        a=a,b=b,c=c,y=underside,
                        minX=Mathf.Min(a.x,Mathf.Min(b.x,c.x)),maxX=Mathf.Max(a.x,Mathf.Max(b.x,c.x)),
                        minZ=Mathf.Min(a.z,Mathf.Min(b.z,c.z)),maxZ=Mathf.Max(a.z,Mathf.Max(b.z,c.z))
                    });
                }
            }
        }
        return result;
    }

    private static float Cross(Vector3 a,Vector3 b,Vector3 p)
    { return (b.x-a.x)*(p.z-a.z)-(b.z-a.z)*(p.x-a.x); }

    private static bool CheckOutside(float[] xyz,List<CeilingTriangle> ceilings,out string blocking)
    {
        for(int i=0;i<xyz.Length;i+=9)
        {
            Vector3 a=new Vector3(xyz[i],xyz[i+1],xyz[i+2]);
            Vector3 b=new Vector3(xyz[i+3],xyz[i+4],xyz[i+5]);
            Vector3 c=new Vector3(xyz[i+6],xyz[i+7],xyz[i+8]);
            for(int u=0;u<=4;u++) for(int v=0;v<=4-u;v++)
            {
                Vector3 p=a*(1f-(u+v)/4f)+b*(u/4f)+c*(v/4f);
                foreach(CeilingTriangle t in ceilings)
                {
                    if(p.y>=t.y-.005f || p.x<t.minX || p.x>t.maxX || p.z<t.minZ || p.z>t.maxZ) continue;
                    float s1=Cross(t.a,t.b,p),s2=Cross(t.b,t.c,p),s3=Cross(t.c,t.a,p);
                    if((s1>.00001f && s2>.00001f && s3>.00001f) ||
                       (s1<-.00001f && s2<-.00001f && s3<-.00001f))
                    { blocking=p.ToString("F3"); return false; }
                }
            }
        }
        blocking=null;
        return true;
    }

    private static void Build(string objectName,float[] xyz,Transform parent,Material material)
    {
        var vertices=new List<Vector3>();
        var faces=new List<Face>();
        for(int i=0;i<xyz.Length;i+=9)
        {
            int first=vertices.Count;
            for(int j=0;j<9;j+=3)
                vertices.Add(parent.InverseTransformPoint(new Vector3(xyz[i+j],xyz[i+j+1],xyz[i+j+2])));
            faces.Add(new Face(new[]{first,first+1,first+2}));
        }
        ProBuilderMesh mesh=ProBuilderMesh.Create(vertices,faces);
        SceneManager.MoveGameObjectToScene(mesh.gameObject,parent.gameObject.scene);
        mesh.name=objectName;
        mesh.transform.SetParent(parent,false);
        mesh.transform.localPosition=Vector3.zero;
        mesh.transform.localRotation=Quaternion.identity;
        mesh.transform.localScale=Vector3.one;
        Undo.RegisterCreatedObjectUndo(mesh.gameObject,"Criar faixa de cornija V10");
        mesh.GetComponent<MeshRenderer>().sharedMaterial=material;
        mesh.ToMesh();
        mesh.Refresh();
    }

