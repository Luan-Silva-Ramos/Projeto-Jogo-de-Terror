            Debug.Log("Cornijas superiores V10 criadas. Faixas em 21 trechos do contorno externo; frente interrompida junto ao frontao. Cornija central V08 preservada desativada. Verificacao por amostragem contra os tetos internos concluida. V05, V06, V08/V09 preservadas ativas.",root);
