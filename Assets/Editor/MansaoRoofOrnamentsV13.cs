    [MenuItem("Tools/Mansao/Criar suportes e ornamentos frontais V13")]
    private static void Create()
    {
        if(EditorApplication.isPlayingOrWillChangePlaymode) { Show("Saia do Play Mode primeiro."); return; }
        Transform mansion=Selection.activeTransform;
        while(mansion!=null && mansion.name!="Mansion") mansion=mansion.parent;
        Transform parent=mansion==null?null:mansion.Find("UpperFloor_V2/Exterior_Roofs");
        if(parent==null) { Show("Selecione um objeto da mansao. Exterior_Roofs nao foi encontrado."); return; }
        if(parent.Find("Roof_Ornaments_V13")!=null) { Show("A V13 ja existe. Nenhuma copia foi criada."); return; }
        if(Vector3.Distance(parent.lossyScale,Vector3.one)>.001f)
        { Show("Exterior_Roofs tem escala mundial diferente de 1. Nada foi alterado."); return; }
        Transform upper=parent.Find("Roof_Full_Assembly_V05/Roof_WholeHouse_Joined_V05");
        ProBuilderMesh roof=upper==null?null:upper.GetComponent<ProBuilderMesh>();
        Renderer roofRenderer=upper==null?null:upper.GetComponent<Renderer>();
        Transform cornices=parent.Find("Cornices_Upper_V10");
        if(roof==null || roofRenderer==null || !upper.gameObject.activeInHierarchy ||
            Mathf.Abs(roofRenderer.bounds.max.y-10.2f)>.02f ||
            cornices==null || !cornices.gameObject.activeInHierarchy)
        { Show("Mantenha a cobertura V05 nas medidas originais e as cornijas V10 ativas. Nada foi alterado."); return; }

        Transform eastCeiling=null,westCeiling=null;
        var posts=new Dictionary<string,Renderer>();
        foreach(Transform t in mansion.GetComponentsInChildren<Transform>(true))
        {
            if(!t.gameObject.activeInHierarchy) continue;
            if(t.name=="Ceiling_Upper_MasterRoom") eastCeiling=t;
            if(t.name=="Ceiling_Upper_GuestRoom") westCeiling=t;
            foreach(Site site in Sites)
                if(t.name=="Timber_Post_"+site.name+"_Upper") posts[site.name]=t.GetComponent<Renderer>();
        }
        foreach(Site site in Sites)
        {
            Renderer r;
            if(!posts.TryGetValue(site.name,out r) || r==null ||
                Vector3.Distance(r.bounds.center,site.post)>.025f || Mathf.Abs(r.bounds.size.y-3.5f)>.025f)
            { Show("O pilar "+site.name+" nao esta na posicao conferida. Nada foi alterado."); return; }
        }
        if(eastCeiling==null || westCeiling==null)
        { Show("Nao encontrei os dois tetos internos originais ativos. Nada foi alterado."); return; }
        var footprint=new List<Tri>();
        ReadFootprint(eastCeiling,footprint);
        ReadFootprint(westCeiling,footprint);
        if(footprint.Count==0) { Show("Nao consegui verificar o contorno interno das alas. Nada foi alterado."); return; }
        foreach(Site site in Sites)
        {
            Vector3 anchor=new Vector3(site.post.x,6.6f,site.post.z);
            Matrix4x4 matrix=Matrix4x4.TRS(anchor,Quaternion.LookRotation(site.normal,Vector3.up),Vector3.one);
            if(!CheckSupport(matrix,footprint))
            { Show("Um suporte ultrapassaria o contorno da ala: "+site.name+". Nada foi alterado."); return; }
        }
        var roofTriangles=new List<Tri>();
        ReadTriangles(roof,roofTriangles);
        if(!CheckSeat(new Vector3(7.2f,10.2f,-5.2f),roofTriangles) ||
           !CheckSeat(new Vector3(-7.2f,10.2f,-5.2f),roofTriangles))
        { Show("Nao consegui confirmar o encaixe dos ornamentos nos apices atuais. Nada foi alterado."); return; }

        Material wood=AssetDatabase.LoadAssetAtPath<Material>("Assets/_Game/Art/Materials/M_Wood_Exterior_PBR.mat");
        Shader shader=Shader.Find("Universal Render Pipeline/Lit");
        if(wood==null || shader==null || !AssetDatabase.IsValidFolder("Assets/_Game/Art/Materials"))
        { Show("Nao encontrei a madeira existente, a pasta de materiais ou o shader URP/Lit. Nada foi alterado."); return; }
        const string metalPath="Assets/_Game/Art/Materials/M_Roof_Finial_AgedMetal.mat";
        Material metal=AssetDatabase.LoadAssetAtPath<Material>(metalPath);
        if(metal==null)
        {
            metal=new Material(shader);
            metal.name="M_Roof_Finial_AgedMetal";
            metal.SetColor("_BaseColor",new Color(.18f,.12f,.075f,1f));
            metal.SetFloat("_Metallic",.65f);
            metal.SetFloat("_Smoothness",.32f);
            AssetDatabase.CreateAsset(metal,metalPath);
        }

        Undo.IncrementCurrentGroup();
        int undoGroup=Undo.GetCurrentGroup();
        Undo.SetCurrentGroupName("Criar suportes e ornamentos V13");
        try
        {
            var root=new GameObject("Roof_Ornaments_V13");
            SceneManager.MoveGameObjectToScene(root,upper.gameObject.scene);
            root.transform.SetParent(parent,false);
            Undo.RegisterCreatedObjectUndo(root,"Criar ornamentos V13");
            Transform corbels=Organizer("Corbels_Front_V13",root.transform);
            Transform finials=Organizer("Finials_Front_V13",root.transform);
            foreach(Site site in Sites)
                Build("Corbel_"+site.name+"_V13",Support,new Vector3(site.post.x,6.6f,site.post.z),
                    Quaternion.LookRotation(site.normal,Vector3.up),corbels,wood,false);
            Build("Finial_East_V13",Finial,new Vector3(7.2f,10.2f,-5.2f),Quaternion.identity,finials,metal,true);
            Build("Finial_West_V13",Finial,new Vector3(-7.2f,10.2f,-5.2f),Quaternion.identity,finials,metal,true);
            EditorSceneManager.MarkSceneDirty(upper.gameObject.scene);
            Selection.activeGameObject=root;
            Undo.CollapseUndoOperations(undoGroup);
            Debug.Log("V13 criada: oito suportes curvos frontais e dois ornamentos nos apices. Nenhum conjunto anterior foi desativado. Contorno das alas e encaixe dos ornamentos conferidos. Entalhes complexos, suportes traseiros e demais acabamentos continuam pendentes.",root);
        }
        catch(System.Exception error)
        {
            Undo.RevertAllDownToGroup(undoGroup);
            Debug.LogException(error);
            Show("A montagem foi desfeita devido a um erro. Consulte a Console.");
        }
    }

    private static Transform Organizer(string name,Transform parent)
    {
        var go=new GameObject(name);
        SceneManager.MoveGameObjectToScene(go,parent.gameObject.scene);
        go.transform.SetParent(parent,false);
        Undo.RegisterCreatedObjectUndo(go,"Criar organizador V13");
        return go.transform;
    }
    private static void ReadTriangles(ProBuilderMesh mesh,List<Tri> output)
    {
        foreach(Face f in mesh.faces)
        {
            var ids=f.indexes;
            for(int i=0;i<ids.Count;i+=3)
                output.Add(new Tri {
                    a=mesh.transform.TransformPoint(mesh.positions[ids[i]]),
                    b=mesh.transform.TransformPoint(mesh.positions[ids[i+1]]),
                    c=mesh.transform.TransformPoint(mesh.positions[ids[i+2]]) });
        }
    }
    private static void ReadFootprint(Transform t,List<Tri> output)
    {
        ProBuilderMesh mesh=t.GetComponent<ProBuilderMesh>();
        Renderer renderer=t.GetComponent<Renderer>();
        if(mesh==null || renderer==null) return;
        var all=new List<Tri>();
        ReadTriangles(mesh,all);
        float underside=renderer.bounds.min.y;
        foreach(Tri tri in all)
            if(Mathf.Abs(tri.a.y-underside)<.01f && Mathf.Abs(tri.b.y-underside)<.01f &&
                Mathf.Abs(tri.c.y-underside)<.01f && Mathf.Abs(Cross(tri.a,tri.b,tri.c))>.000001f)
                output.Add(tri);
    }
    private static float Cross(Vector3 a,Vector3 b,Vector3 p)
    { return (b.x-a.x)*(p.z-a.z)-(b.z-a.z)*(p.x-a.x); }
    private static bool Inside(Tri t,Vector3 p)
    {
        float a=Cross(t.a,t.b,p),b=Cross(t.b,t.c,p),c=Cross(t.c,t.a,p);
        return (a>.00001f && b>.00001f && c>.00001f) ||
               (a<-.00001f && b<-.00001f && c<-.00001f);
    }
    private static bool CheckSupport(Matrix4x4 matrix,List<Tri> footprint)
    {
        for(int i=0;i<Support.Length;i+=9)
        {
            Vector3 a=matrix.MultiplyPoint3x4(new Vector3(Support[i],Support[i+1],Support[i+2]));
            Vector3 b=matrix.MultiplyPoint3x4(new Vector3(Support[i+3],Support[i+4],Support[i+5]));
            Vector3 c=matrix.MultiplyPoint3x4(new Vector3(Support[i+6],Support[i+7],Support[i+8]));
            for(int u=0;u<=4;u++) for(int v=0;v<=4-u;v++)
            {
                Vector3 p=a*(1f-(u+v)/4f)+b*(u/4f)+c*(v/4f);
                foreach(Tri t in footprint) if(Inside(t,p)) return false;
            }
        }
        return true;
    }
    private static bool CheckSeat(Vector3 anchor,List<Tri> roof)
    {
        for(int i=0;i<32;i++)
        {
            float angle=i*Mathf.PI*2f/32f;
            Vector3 p=anchor+new Vector3(.20f*Mathf.Cos(angle),-.18f,.20f*Mathf.Sin(angle));
            float top=float.NegativeInfinity;
            foreach(Tri t in roof)
            {
                float area=Cross(t.a,t.b,t.c);
                if(Mathf.Abs(area)<.000001f) continue;
                float wa=Cross(t.b,t.c,p)/area,wb=Cross(t.c,t.a,p)/area,wc=1f-wa-wb;
                if(wa>=-.0001f && wb>=-.0001f && wc>=-.0001f)
                    top=Mathf.Max(top,wa*t.a.y+wb*t.b.y+wc*t.c.y);
            }
            if(float.IsNegativeInfinity(top) || p.y>top+.005f || top-p.y>.12f) return false;
        }
        return true;
    }
    private static void Build(string name,float[] xyz,Vector3 anchor,Quaternion rotation,
        Transform parent,Material material,bool smooth)
    {
        var vertices=new List<Vector3>();
        var faces=new List<Face>();
        for(int i=0;i<xyz.Length;i+=9)
        {
            int first=vertices.Count;
            for(int j=0;j<9;j+=3) vertices.Add(new Vector3(xyz[i+j],xyz[i+j+1],xyz[i+j+2]));
            var face=new Face(new[]{first,first+1,first+2});
            if(smooth) face.smoothingGroup=1;
            faces.Add(face);
        }
        ProBuilderMesh mesh=ProBuilderMesh.Create(vertices,faces);
        SceneManager.MoveGameObjectToScene(mesh.gameObject,parent.gameObject.scene);
        mesh.name=name;
        mesh.transform.SetParent(parent,false);
        mesh.transform.position=anchor;
        mesh.transform.rotation=rotation;
        mesh.transform.localScale=Vector3.one;
        Undo.RegisterCreatedObjectUndo(mesh.gameObject,"Criar peca ornamental V13");
        mesh.GetComponent<MeshRenderer>().sharedMaterial=material;
        mesh.ToMesh();
        mesh.Refresh();
    }
