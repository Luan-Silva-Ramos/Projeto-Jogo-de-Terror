            root.transform.SetParent(parent, false);
            Undo.RegisterCreatedObjectUndo(root, "Criar conjunto V03");
            Build("Roof_CentralEast_Joined_V03", RoofCoordinates, root.transform, sourceRenderer.sharedMaterial);
