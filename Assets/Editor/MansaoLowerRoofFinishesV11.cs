    [MenuItem("Tools/Mansao/Acabar telhados baixos V11")]
    private static void Create()
    {
        if(EditorApplication.isPlayingOrWillChangePlaymode) { Show("Saia do Play Mode primeiro."); return; }
        Transform mansion=Selection.activeTransform;
        while(mansion!=null && mansion.name!="Mansion") mansion=mansion.parent;
        Transform parent=mansion==null?null:mansion.Find("UpperFloor_V2/Exterior_Roofs");
        if(parent==null) { Show("Selecione um objeto da mansao. Exterior_Roofs nao foi encontrado."); return; }
        if(parent.Find("Roof_Lower_Finishes_V11")!=null) { Show("A V11 ja existe. Nenhuma copia foi criada."); return; }
        Transform v06=parent.Find("Roof_Corrections_V06");
        if(v06==null || !v06.gameObject.activeInHierarchy) { Show("Mantenha Roof_Corrections_V06 ativa. Nada foi alterado."); return; }
        string[] names={"Roof_Lower_ServiceWest_V06","Roof_Lower_ServiceRear_V06","Roof_Lower_Pantry_V06"};
        Vector3[] mins={new Vector3(-12.5f,3.68f,.98f),new Vector3(-12.5f,3.68f,11.68f),new Vector3(-7.35f,3.68f,11.68f)};
        Vector3[] maxs={new Vector3(-10.18f,4.25f,12.3f),new Vector3(-7.35f,4.25f,12.3f),new Vector3(-4.15f,4.25f,13.7f)};
        for(int i=0;i<names.Length;i++)
        {
            Transform t=v06.Find(names[i]);
            Renderer r=t==null?null:t.GetComponent<Renderer>();
            if(r==null || !t.gameObject.activeInHierarchy ||
                Vector3.Distance(r.bounds.min,mins[i])>.025f || Vector3.Distance(r.bounds.max,maxs[i])>.025f)
            { Show("As medidas de "+names[i]+" diferem da V06 consultada. Nada foi alterado."); return; }
        }
        Material wood=AssetDatabase.LoadAssetAtPath<Material>("Assets/_Game/Art/Materials/M_Wood_Exterior_PBR.mat");
        Shader shader=Shader.Find("Universal Render Pipeline/Lit");
        if(wood==null || shader==null || !AssetDatabase.IsValidFolder("Assets/_Game/Art/Materials"))
        { Show("Nao encontrei o material de madeira, a pasta de materiais ou o shader URP/Lit. Nada foi alterado."); return; }

        // Verificacao conservadora por amostragem contra o centro dos volumes superiores.
        // Recuo de 30 cm corresponde a espessura registrada das paredes externas.
        var interiors=new List<Bounds>();
        foreach(Transform t in mansion.GetComponentsInChildren<Transform>(true))
        {
            if(!t.gameObject.activeInHierarchy || !t.name.StartsWith("Ceiling_Upper_")) continue;
            Renderer r=t.GetComponent<Renderer>();
            if(r==null) continue;
            Bounds b=r.bounds;
            if(b.size.x<=.60f || b.size.z<=.60f) continue;
            Vector3 min=b.min,max=b.max;
            min.x+=.30f; max.x-=.30f; min.z+=.30f; max.z-=.30f;
            min.y=3.70f; max.y=b.min.y-.005f;
            if(max.y>min.y) { Bounds room=new Bounds(); room.SetMinMax(min,max); interiors.Add(room); }
        }
        if(interiors.Count==0) { Show("Nao consegui conferir os volumes internos superiores. Nada foi alterado."); return; }
        float[][] arrays={UpperCap,MainFascia,LowerBead,WallFlashing,StepFlashing};
        foreach(float[] xyz in arrays)
            if(!CheckOutside(xyz,interiors))
            { Show("Uma peca encontrou o volume interno previsto. Nada foi alterado."); return; }

        string materialPath="Assets/_Game/Art/Materials/M_Roof_Flashing_Dark.mat";
        Material metal=AssetDatabase.LoadAssetAtPath<Material>(materialPath);
        if(metal==null)
        {
            metal=new Material(shader);
            metal.name="M_Roof_Flashing_Dark";
            metal.SetColor("_BaseColor",new Color(.16f,.17f,.18f,1f));
            metal.SetFloat("_Metallic",.45f);
            metal.SetFloat("_Smoothness",.35f);
            AssetDatabase.CreateAsset(metal,materialPath);
        }
        Undo.IncrementCurrentGroup();
        int group=Undo.GetCurrentGroup();
        Undo.SetCurrentGroupName("Acabar telhados baixos V11");
        try
        {
            var root=new GameObject("Roof_Lower_Finishes_V11");
            SceneManager.MoveGameObjectToScene(root,v06.gameObject.scene);
            root.transform.SetParent(parent,false);
            Undo.RegisterCreatedObjectUndo(root,"Criar acabamentos V11");
            Build("LowerRoof_UpperCap_V11",UpperCap,root.transform,wood);
            Build("LowerRoof_MainFascia_V11",MainFascia,root.transform,wood);
            Build("LowerRoof_LowerBead_V11",LowerBead,root.transform,wood);
            Build("LowerRoof_WallFlashing_V11",WallFlashing,root.transform,metal);
            Build("LowerRoof_StepFlashing_V11",StepFlashing,root.transform,metal);
            EditorSceneManager.MarkSceneDirty(v06.gameObject.scene);
            Selection.activeGameObject=root;
            Undo.CollapseUndoOperations(group);
            Debug.Log("V11 criada: tres faixas nas bordas livres dos telhados baixos, rufos junto as paredes e arremate do degrau despensa/retorno. V06 e demais conjuntos preservados ativos. Janelas, portas, tetos e jardim nao foram alterados. Calhas, condutores e materiais definitivos dos telhados ainda pendentes.",root);
        }
        catch(System.Exception error)
        {
            Undo.RevertAllDownToGroup(group);
            Debug.LogException(error);
            Show("A montagem foi desfeita devido a um erro. Consulte a Console.");
        }
    }

    private static bool CheckOutside(float[] xyz,List<Bounds> interiors)
    {
        for(int i=0;i<xyz.Length;i+=9)
        {
            Vector3 a=new Vector3(xyz[i],xyz[i+1],xyz[i+2]);
            Vector3 b=new Vector3(xyz[i+3],xyz[i+4],xyz[i+5]);
            Vector3 c=new Vector3(xyz[i+6],xyz[i+7],xyz[i+8]);
            for(int u=0;u<=4;u++) for(int v=0;v<=4-u;v++)
            {
                Vector3 p=a*(1f-(u+v)/4f)+b*(u/4f)+c*(v/4f);
                if(p.y<3.55f) return false; // Margem acima do teto interno terreo Y 3.50.
                foreach(Bounds room in interiors) if(room.Contains(p)) return false;
            }
        }
        return true;
    }

    private static void Build(string objectName,float[] xyz,Transform parent,Material material)
    {
        var vertices=new List<Vector3>();
        var faces=new List<Face>();
        for(int i=0;i<xyz.Length;i+=9)
        {
            int first=vertices.Count;
            for(int j=0;j<9;j+=3)
                vertices.Add(parent.InverseTransformPoint(new Vector3(xyz[i+j],xyz[i+j+1],xyz[i+j+2])));
            faces.Add(new Face(new[]{first,first+1,first+2}));
        }
        ProBuilderMesh mesh=ProBuilderMesh.Create(vertices,faces);
        SceneManager.MoveGameObjectToScene(mesh.gameObject,parent.gameObject.scene);
        mesh.name=objectName;
        mesh.transform.SetParent(parent,false);
        mesh.transform.localPosition=Vector3.zero;
        mesh.transform.localRotation=Quaternion.identity;
        mesh.transform.localScale=Vector3.one;
        Undo.RegisterCreatedObjectUndo(mesh.gameObject,"Criar acabamento de telhado V11");
        mesh.GetComponent<MeshRenderer>().sharedMaterial=material;
        mesh.ToMesh();
        mesh.Refresh();
    }

