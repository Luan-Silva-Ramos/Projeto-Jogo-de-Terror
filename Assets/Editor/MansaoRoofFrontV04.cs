    private static void Build(string objectName, float[] xyz, Transform parent, Material material)
    {
        var positions = new List<Vector3>();
        var faces = new List<Face>();
        for (int i = 0; i < xyz.Length; i += 9)
        {
            int first = positions.Count;
            for (int j = 0; j < 9; j += 3)
                positions.Add(parent.InverseTransformPoint(new Vector3(xyz[i+j],xyz[i+j+1],xyz[i+j+2])));
            faces.Add(new Face(objectName == "Fronton_Central_Base_V04"
                ? new[] {first, first+2, first+1} : new[] {first, first+1, first+2}));
        }
        ProBuilderMesh mesh = ProBuilderMesh.Create(positions, faces);
        SceneManager.MoveGameObjectToScene(mesh.gameObject, parent.gameObject.scene);
        mesh.name = objectName;
        mesh.transform.SetParent(parent, false);
        mesh.transform.localPosition = Vector3.zero;
        mesh.transform.localRotation = Quaternion.identity;
        mesh.transform.localScale = Vector3.one;
        Undo.RegisterCreatedObjectUndo(mesh.gameObject, "Criar malha V04");
        if (material != null) mesh.GetComponent<MeshRenderer>().sharedMaterial = material;
        mesh.ToMesh();
        mesh.Refresh();
    }

