    [MenuItem("Tools/Mansao/Integrar frontao a janela V08")]
    private static void Create()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode)
        { Show("Saia do Play Mode primeiro."); return; }
        Transform mansion=Selection.activeTransform;
        while(mansion!=null && mansion.name!="Mansion") mansion=mansion.parent;
        Transform parent=mansion==null?null:mansion.Find("UpperFloor_V2/Exterior_Roofs");
        if(parent==null) { Show("Selecione um objeto da mansao. Exterior_Roofs nao foi encontrado."); return; }
        if(parent.Find("Fronton_Central_Integrated_V08")!=null)
        { Show("A V08 ja existe. Nenhuma copia foi criada."); return; }
        Transform v05=parent.Find("Roof_Full_Assembly_V05");
        Transform roof=v05==null?null:v05.Find("Roof_WholeHouse_Joined_V05");
        Renderer roofRenderer=roof==null?null:roof.GetComponent<Renderer>();
        if(roofRenderer==null || !roof.gameObject.activeInHierarchy ||
            Mathf.Abs(roofRenderer.bounds.max.y-10.2f)>.025f ||
            Mathf.Abs(roofRenderer.bounds.min.z+8.75f)>.025f)
        { Show("A cobertura V05 precisa estar ativa e nas posicoes originais. Nada foi alterado."); return; }
        Transform oldCornice=null,window=null;
        foreach(Transform t in mansion.GetComponentsInChildren<Transform>(true))
        {
            if(t.name=="Facade_Atrium_Cornice") oldCornice=t;
            if(t.name=="PF_Window_Front_Ornate") window=t;
        }
        Renderer corniceRenderer=oldCornice==null?null:oldCornice.GetComponent<Renderer>();
        if(corniceRenderer==null || Mathf.Abs(corniceRenderer.bounds.min.x+3.9f)>.025f ||
            Mathf.Abs(corniceRenderer.bounds.max.x-3.9f)>.025f ||
            Mathf.Abs(corniceRenderer.bounds.min.y-7f)>.025f ||
            Mathf.Abs(corniceRenderer.bounds.max.y-7.2f)>.025f ||
            Mathf.Abs(corniceRenderer.bounds.min.z+5.02f)>.025f)
        { Show("Nao encontrei Facade_Atrium_Cornice nas medidas consultadas. Nada foi alterado."); return; }
        if(window==null || !window.gameObject.activeInHierarchy)
        { Show("Nao encontrei a janela PF_Window_Front_Ornate ativa. Nada foi alterado."); return; }
        Renderer[] windowParts=window.GetComponentsInChildren<Renderer>();
        if(windowParts.Length==0) { Show("Nao foi possivel conferir a janela. Nada foi alterado."); return; }
        Bounds windowBounds=windowParts[0].bounds;
        foreach(Renderer r in windowParts) windowBounds.Encapsulate(r.bounds);
        // Abertura central no novo preenchimento: X -1.38..1.38, ate Y 7.02.
        if(windowBounds.min.x< -1.33f || windowBounds.max.x>1.33f || windowBounds.max.y>6.98f)
        {
            Show("A janela excede a folga prevista. Nada foi alterado. Limites encontrados: X "+
                windowBounds.min.x.ToString("F3")+" a "+windowBounds.max.x.ToString("F3")+
                ", topo Y "+windowBounds.max.y.ToString("F3")+".");
            return;
        }
        Material wood=AssetDatabase.LoadAssetAtPath<Material>("Assets/_Game/Art/Materials/M_Wood_Exterior_PBR.mat");
        Material plaster=AssetDatabase.LoadAssetAtPath<Material>("Assets/_Game/Art/Materials/M_Plaster_Exterior.mat");
        if(wood==null || plaster==null) { Show("Nao encontrei os materiais existentes de madeira e reboco. Nada foi alterado."); return; }
        Undo.IncrementCurrentGroup();
        int group=Undo.GetCurrentGroup();
        Undo.SetCurrentGroupName("Integrar frontao a janela V08");
        try
        {
            GameObject root=new GameObject("Fronton_Central_Integrated_V08");
            SceneManager.MoveGameObjectToScene(root,v05.gameObject.scene);
            root.transform.SetParent(parent,false);
            Undo.RegisterCreatedObjectUndo(root,"Criar frontao integrado V08");
            Build("Fronton_Integrated_Plaster_V08",Plaster,root.transform,plaster);
            Build("Fronton_Integrated_Roof_V08",Roof,root.transform,roofRenderer.sharedMaterial);
            Build("Fronton_CurvedFrame_AndLegs_V08",Timber,root.transform,wood);
            Build("Cornice_Central_LeftRight_V08",Cornices,root.transform,wood);
            Transform v07=parent.Find("Fronton_Central_Curved_V07");
            if(v07!=null) SetInactive(v07.gameObject);
            Transform oldTriangle=v05.Find("Fronton_Central_Base_V05");
            if(oldTriangle!=null) SetInactive(oldTriangle.gameObject);
            SetInactive(oldCornice.gameObject);
            EditorSceneManager.MarkSceneDirty(v05.gameObject.scene);
            Selection.activeGameObject=root;
            Undo.CollapseUndoOperations(group);
            Debug.Log("V08 criada: curva acentuada, laterais prolongadas, preenchimento com folga para a janela e cornija dividida. V07 e cornija original preservadas desativadas. V05/V06, janela e porta preservadas.",root);
        }
        catch(System.Exception error)
        {
            Undo.RevertAllDownToGroup(group);
            Debug.LogException(error);
            Show("A montagem foi desfeita devido a um erro. Consulte a Console.");
        }
    }

    private static void Show(string message) { EditorUtility.DisplayDialog("Frontao V08",message,"OK"); }
    private static void SetInactive(GameObject target)
    {
        Undo.RecordObject(target,"Preservar original");
        target.SetActive(false);
    }
    private static void Build(string objectName,float[] xyz,Transform parent,Material material)
    {
        var vertices=new List<Vector3>();
        var faces=new List<Face>();
        for(int i=0;i<xyz.Length;i+=9)
        {
            int first=vertices.Count;
            for(int j=0;j<9;j+=3)
                vertices.Add(parent.InverseTransformPoint(new Vector3(xyz[i+j],xyz[i+j+1],xyz[i+j+2])));
            faces.Add(new Face(new[]{first,first+1,first+2}));
        }
        ProBuilderMesh mesh=ProBuilderMesh.Create(vertices,faces);
        SceneManager.MoveGameObjectToScene(mesh.gameObject,parent.gameObject.scene);
        mesh.name=objectName;
        mesh.transform.SetParent(parent,false);
        mesh.transform.localPosition=Vector3.zero;
        mesh.transform.localRotation=Quaternion.identity;
        mesh.transform.localScale=Vector3.one;
        Undo.RegisterCreatedObjectUndo(mesh.gameObject,"Criar malha frontao V08");
        mesh.GetComponent<MeshRenderer>().sharedMaterial=material;
        mesh.ToMesh();
        mesh.Refresh();
    }

