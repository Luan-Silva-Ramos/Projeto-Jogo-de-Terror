    [MenuItem("Tools/Mansao/Fechar encontros e criar telhados baixos V06")]
    private static void Create()
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode)
        { Show("Saia do Play Mode primeiro."); return; }
        Transform mansion = Selection.activeTransform;
        while (mansion != null && mansion.name != "Mansion") mansion = mansion.parent;
        Transform parent = mansion == null ? null : mansion.Find("UpperFloor_V2/Exterior_Roofs");
        if (parent == null) { Show("Selecione um objeto da mansao. Exterior_Roofs nao foi encontrado."); return; }
        Transform v05 = parent.Find("Roof_Full_Assembly_V05");
        Transform existing = parent.Find("Roof_Corrections_V06");
        if (existing != null) { Show("Roof_Corrections_V06 ja existe. Nao criei outra copia."); return; }
        Transform upper = v05 == null ? null : v05.Find("Roof_WholeHouse_Joined_V05");
        Renderer upperRenderer = upper == null ? null : upper.GetComponent<Renderer>();
        if (upperRenderer == null || !upper.gameObject.activeInHierarchy ||
            Mathf.Abs(upperRenderer.bounds.max.y - 10.2f) > .03f ||
            Mathf.Abs(upperRenderer.bounds.max.z - 11.95f) > .03f ||
            Mathf.Abs(upperRenderer.bounds.min.z + 8.75f) > .03f)
        { Show("A V05 precisa estar ativa e nas medidas originais para receber estes fechamentos. Nada foi alterado."); return; }

        string[] names = { "Ceiling_Service_West_Main", "Ceiling_Service_Rear", "Ceiling_Pantry" };
        Vector3[] expectedMin = { new Vector3(-12.3f,3.5f,1.2f), new Vector3(-10.2f,3.5f,11.7f), new Vector3(-7.15f,3.5f,11.7f) };
        Vector3[] expectedMax = { new Vector3(-10.2f,3.7f,12.1f), new Vector3(-7.15f,3.7f,12.1f), new Vector3(-4.35f,3.7f,13.5f) };
        for (int i = 0; i < names.Length; i++)
        {
            Renderer found = null;
            foreach (Transform t in mansion.GetComponentsInChildren<Transform>(true))
                if (t.name == names[i] && t.gameObject.activeInHierarchy) { found = t.GetComponent<Renderer>(); break; }
            if (found == null || Vector3.Distance(found.bounds.min,expectedMin[i]) > .04f ||
                Vector3.Distance(found.bounds.max,expectedMax[i]) > .04f)
            { Show("As medidas de " + names[i] + " diferem das medidas consultadas. Nada foi alterado."); return; }
        }

        Material plaster = AssetDatabase.LoadAssetAtPath<Material>("Assets/_Game/Art/Materials/M_Plaster_Exterior.mat");
        Material wood = AssetDatabase.LoadAssetAtPath<Material>("Assets/_Game/Art/Materials/M_Wood_Exterior_PBR.mat");
        if (plaster == null) plaster = upperRenderer.sharedMaterial;
        if (wood == null) wood = plaster;
        Undo.IncrementCurrentGroup();
        int group = Undo.GetCurrentGroup();
        Undo.SetCurrentGroupName("Fechar encontros e criar telhados baixos V06");
        try
        {
            GameObject root = new GameObject("Roof_Corrections_V06");
            SceneManager.MoveGameObjectToScene(root, v05.gameObject.scene);
            root.transform.SetParent(parent,false);
            Undo.RegisterCreatedObjectUndo(root,"Criar correcoes V06");
            Build("Roof_Junction_Closures_V06",Closures,null,root.transform,plaster,plaster);
            Build("Roof_Lower_ServiceWest_V06",WestTop,WestSides,root.transform,upperRenderer.sharedMaterial,wood);
            Build("Roof_Lower_ServiceRear_V06",RearTop,RearSides,root.transform,upperRenderer.sharedMaterial,wood);
            Build("Roof_Lower_Pantry_V06",PantryTop,PantrySides,root.transform,upperRenderer.sharedMaterial,wood);
            EditorSceneManager.MarkSceneDirty(v05.gameObject.scene);
            Selection.activeGameObject = root;
            Undo.CollapseUndoOperations(group);
            Debug.Log("V06 adicionada: fechamentos dos desniveis superiores e telhados baixos oeste/despensa. V05 continua ativa. Tetos internos, janelas, portas e jardim preservados. Materiais de cobertura, rufos, calhas e cornijas ainda pendentes.",root);
        }
        catch (System.Exception error)
        {
            Undo.RevertAllDownToGroup(group);
            Debug.LogException(error);
            Show("A montagem foi desfeita devido a um erro. Consulte a Console.");
        }
    }

    private static void Show(string message) { EditorUtility.DisplayDialog("Telhados V06",message,"OK"); }

    private static void Build(string name, float[] first, float[] second, Transform parent, Material top, Material side)
    {
        var vertices = new List<Vector3>();
        var faces = new List<Face>();
        Append(first,0,parent,vertices,faces);
        if (second != null) Append(second,1,parent,vertices,faces);
        ProBuilderMesh mesh = ProBuilderMesh.Create(vertices,faces);
        SceneManager.MoveGameObjectToScene(mesh.gameObject,parent.gameObject.scene);
        mesh.name = name;
        mesh.transform.SetParent(parent,false);
        mesh.transform.localPosition = Vector3.zero;
        mesh.transform.localRotation = Quaternion.identity;
        mesh.transform.localScale = Vector3.one;
        Undo.RegisterCreatedObjectUndo(mesh.gameObject,"Criar malha V06");
        mesh.GetComponent<MeshRenderer>().sharedMaterials = second == null ? new[]{top} : new[]{top,side};
        mesh.ToMesh();
        mesh.Refresh();
    }

    private static void Append(float[] xyz,int material,Transform parent,List<Vector3> vertices,List<Face> faces)
    {
        for (int i=0; i<xyz.Length; i+=9)
        {
            int first=vertices.Count;
            for (int j=0;j<9;j+=3)
                vertices.Add(parent.InverseTransformPoint(new Vector3(xyz[i+j],xyz[i+j+1],xyz[i+j+2])));
            var face=new Face(new[]{first,first+1,first+2});
            face.submeshIndex=material;
            faces.Add(face);
        }
    }

